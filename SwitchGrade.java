public class SwitchGrade {
    public static void main(String[] args){
        char grade = 'C';
        switch (grade)
         {
            case 'A' : System.out.println("excellent -> distinction");
            case 'B' : System.out.println("good -> first class");
            case 'C' : System.out.println("bad -> fail");
        }
    }
    
}
